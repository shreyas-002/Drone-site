/**
 * Generate a single simulated detection for the live feed.
 * Returns an object mimicking a real-time YOLO detection.
 */
export const generateSimulatedDetection = (baseLat = 26.827, baseLng = 75.565, offset = 0) => {
  const isDisease = Math.random() > 0.35;
  const names = isDisease ? DISEASE_NAMES : PEST_NAMES;
  const name = names[Math.floor(Math.random() * names.length)];
  const confidence = parseFloat((0.40 + Math.random() * 0.50).toFixed(2));

  // Random bounding box position (as percentage of frame)
  const x = 8 + Math.random() * 60;
  const y = 8 + Math.random() * 55;
  const w = 12 + Math.random() * 22;
  const h = 12 + Math.random() * 22;

  return {
    id: Date.now() + Math.random(),
    type: isDisease ? "DISEASE" : "PEST",
    name,
    confidence,
    box: { x, y, w, h },
    latitude: baseLat + offset * 0.000002,
    longitude: baseLng + offset * 0.000002,
    timestamp: new Date().toLocaleTimeString("en-IN", { hour12: false }),
    createdAt: Date.now(),
    ttl: 3000 + Math.random() * 2000,
  };
};
